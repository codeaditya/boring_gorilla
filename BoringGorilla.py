#!/usr/bin/python3
# -*- coding: utf-8 -*-

import csv
import datetime
import logging
import os.path
import sys

from PyQt4 import QtCore, QtGui

from BoringGorilla_design import Ui_BoringGorilla
from preferences import PreferencesDialog, process_config
import helpers

import trader

###############################################################################
#### Add logging functionality ################################################
FORMATTER = logging.Formatter("{asctime} - {module:15s} - {process} - "
                              "{levelname:8s} - {message}", style="{")
LOGGING_LEVEL = logging.INFO
logger = logging.getLogger("trader")
logger.setLevel(LOGGING_LEVEL)
logger_preferences = logging.getLogger("preferences")
logger_preferences.setLevel(LOGGING_LEVEL)
logger_helpers = logging.getLogger("helpers")
logger_helpers.setLevel(LOGGING_LEVEL)
###############################################################################


class BoringGorilla(QtGui.QMainWindow):
    """The application to download and process data for Stock Markets.

    :param parent:
    :type parent:
    """
    def __init__(self, parent=None):
        QtGui.QWidget.__init__(self, parent)
        # Load the UI as generated by Qt Designer
        self.ui = Ui_BoringGorilla()
        self.ui.setupUi(self)
        # Properties updated after calling the methods of BoringGorilla
        self.monospace_font = None
        self.trader_thread = None
        self.ami_thread = None
        self.generate_indices_thread = None
        self.dummy_emitter = None
        self.gui_log_handler = None
        self.start_date = datetime.datetime
        self.end_date = datetime.datetime
        self.current_date = datetime.datetime
        self.time_delta = datetime.timedelta(days=1)
        self.ignore_weekend = bool
        self.nse_indices = bool
        self.nse_equities = bool
        self.nse_futures = bool
        self.debugging = bool
        self.file_location = str
        # Config properties updated after reading the config file
        self.gorilla_config = object
        self.nse_indices_folder = str
        self.nse_equities_folder = str
        self.nse_futures_folder = str
        self.downloads_folder = str
        self.ami_eod_db_folder = str
        self.ami_intraday_db_folder = str
        self.ami_installation_folder = str
        self.import_selected_nse_futures = bool
        self.personal_nifty_index_file = str
        self.personal_nifty_futures_file = str
        self.preserve_downloads = bool
        # Other Initialization stuff
        self.ami_import_file_list = []
        self.nse_futures_file_list = []
        self.output_data = []
        self.selected_nse_futures_data = []
        self.selected_nse_futures_scrips = []
        self.ami_import_format_eod = "boring_gorilla_eod.format"
        self.config_filename = 'config.ini'
        self.config = process_config(self.config_filename)
        self.initial_ui_changes()
        self.create_worker_threads()
        self.create_gui_log_handler()
        self.map_signals_and_slots()
        self.get_config_values()
        logger.debug("UI loaded.")

    def initial_ui_changes(self):
        """
        The initial changes to be made to UI when application starts.
        """
        # Current Date
        self.ui.start_date.setDate(QtCore.QDate.currentDate())
        self.ui.end_date.setDate(QtCore.QDate.currentDate())
        # Maximum Date allowed
        self.ui.start_date.setMaximumDate(QtCore.QDate.currentDate())
        self.ui.end_date.setMaximumDate(QtCore.QDate.currentDate())
        # Monospace font for log widget
        self.monospace_font = QtGui.QFont("Monospace")
        # StyleHint is required for Windows, otherwise it shows up in
        # normal font
        self.monospace_font.setStyleHint(QtGui.QFont.TypeWriter)
        self.ui.log_browser.setCurrentFont(self.monospace_font)

    def create_worker_threads(self):
        """
        Create the worker threads for time-consuming functions.
        """
        self.trader_thread = helpers.WorkerThread(self.start_download, ())
        self.ami_thread = helpers.WorkerThread(self.import_in_ami, ())
        self.generate_indices_thread = helpers.WorkerThread(
            self.generate_indices, ())

    def create_gui_log_handler(self):
        """
        Add all the logger instances to GuiLogHandler which emits the
        log messages in realtime.
        """
        self.dummy_emitter = QtCore.QObject()
        self.gui_log_handler = helpers.GuiLogHandler(self.dummy_emitter)
        self.gui_log_handler.setFormatter(FORMATTER)
        logger.addHandler(self.gui_log_handler)
        logger_preferences.addHandler(self.gui_log_handler)
        logger_helpers.addHandler(self.gui_log_handler)

    def map_signals_and_slots(self):
        """
        Map all the signals and slots which aren't mapped in
        auto-generated code.
        """
        self.ui.process_button.clicked.connect(self.process_button_pressed)
        self.ui.import_in_ami_button.clicked.connect(self.import_in_ami_pressed)
        self.ui.generate_indices_button.clicked.connect(self.generate_indices_pressed)
        self.trader_thread.finished.connect(self.restore_ui)
        self.trader_thread.terminated.connect(self.restore_ui)
        self.ami_thread.finished.connect(self.restore_ui)
        self.ami_thread.terminated.connect(self.restore_ui)
        self.generate_indices_thread.finished.connect(self.restore_ui)
        self.generate_indices_thread.terminated.connect(self.restore_ui)
        self.connect(self.dummy_emitter, QtCore.SIGNAL("log_msg(QString)"),
                     self.ui.log_browser.append)
        self.ui.actionPreferences.triggered.connect(self.show_preferences_dialog)

    def read_config(self):
        """
        Read the config file.
        """
        self.config.read(self.config_filename)

    def get_config_values(self):
        self.read_config()
        self.gorilla_config = self.config["boring_gorilla"]
        self.nse_indices_folder = self.gorilla_config.get("nse_indices_folder")
        self.nse_equities_folder = self.gorilla_config.get("nse_equities_folder")
        self.nse_futures_folder = self.gorilla_config.get("nse_futures_folder")
        self.downloads_folder = self.gorilla_config.get("downloads_folder")
        self.ami_eod_db_folder = self.gorilla_config.get("ami_eod_db_folder")
        self.ami_intraday_db_folder = self.gorilla_config.get("ami_intraday_db_folder")
        self.ami_installation_folder = self.gorilla_config.get("ami_installation_folder")
        self.import_selected_nse_futures = self.gorilla_config.getboolean("import_selected_nse_futures")
        self.personal_nifty_index_file = self.gorilla_config.get("personal_nifty_index_file")
        self.personal_nifty_futures_file = self.gorilla_config.get("personal_nifty_futures_file")
        self.preserve_downloads = self.gorilla_config.getboolean("preserve_downloads")

    def get_ui_values(self):
        """
        Update properties to the latest values in UI.
        """
        self.start_date = self.ui.start_date.dateTime().toPyDateTime()
        self.end_date = self.ui.end_date.dateTime().toPyDateTime()
        self.current_date = self.start_date
        self.ignore_weekend = self.ui.ignore_weekend.isChecked()
        self.nse_indices = self.ui.nse_indices.isChecked()
        self.nse_equities = self.ui.nse_equities.isChecked()
        self.nse_futures = self.ui.nse_futures.isChecked()
        self.debugging = self.ui.debugging.isChecked()

    def disable_ui_widgets(self, status=True):
        """
        Disable the UI widgets. To be called when running threaded
        functions.

        :type status: bool
        """
        self.ui.date_group.setDisabled(status)
        self.ui.segment_group.setDisabled(status)
        self.ui.debugging.setDisabled(status)
        self.ui.process_button.setDisabled(status)
        self.ui.import_in_ami_button.setDisabled(status)
        self.ui.generate_indices_button.setDisabled(status)

    def process_button_pressed(self):
        """
        Disable UI widgets and start the worker thread.
        """
        self.disable_ui_widgets(True)
        self.trader_thread.start()

    def import_in_ami_pressed(self):
        """
        Disable UI widgets and start the worker thread.
        """
        self.disable_ui_widgets(True)
        self.ami_thread.start()

    def generate_indices_pressed(self):
        """
        Disable UI widgets and start the worker thread.
        """
        self.disable_ui_widgets(True)
        self.generate_indices_thread.start()

    def restore_ui(self):
        """
        Re-enable the disabled widgets.
        """
        self.disable_ui_widgets(False)

    def start_download(self):
        """
        The main method for the trader_thread. Processes the data for
        different Exchange/Segments.
        """
        logger.info("Downloading...")
        self.get_ui_values()
        self.log_window_state()
        self.get_config_values()
        trader.DEBUGGING = self.debugging
        if self.nse_indices:
            trader.process_nse_indices(
                self.start_date, self.end_date,
                download_location=self.downloads_folder,
                output_location=self.nse_indices_folder,
                ignore_weekend=self.ignore_weekend
            )
        if self.nse_equities:
            trader.process_nse_equities(
                self.start_date, self.end_date,
                download_location=self.downloads_folder,
                output_location=self.nse_equities_folder,
                ignore_weekend=self.ignore_weekend
            )
        if self.nse_futures:
            trader.process_nse_futures(
                self.start_date, self.end_date,
                download_location=self.downloads_folder,
                output_location=self.nse_futures_folder,
                ignore_weekend=self.ignore_weekend
            )
        logger.info("Download finished...")

    def import_in_ami(self):
        """
        The main method for the ami_thread. Uses the COM interface to
        connect to AmiBroker and import the data therein.
        """
        logger.info("Importing the data in AmiBroker...")
        self.get_ui_values()
        self.log_window_state()
        self.get_config_values()
        self.get_ami_import_file_list()
        helpers.DEBUGGING = self.debugging
        if not self.ami_import_file_list:
            logger.warning("Nothing to import.")
        else:
            helpers.import_data_in_amibroker(
                database_path=self.ami_eod_db_folder,
                import_file_list=self.ami_import_file_list,
                import_format=self.ami_import_format_eod,
                amibroker_visibility=True
            )
            if os.path.exists("selected_nse_futures.csv"):
                os.remove("selected_nse_futures.csv")
        logger.info("Import finished...")

    def get_ami_import_file_list(self):
        """
        Returns a list of file paths to be imported in Amibroker.
        """
        self.get_ui_values()
        self.get_config_values()
        self.ami_import_file_list = []
        self.nse_futures_file_list = []
        if self.nse_indices:
            self.loop_through_dates_to(self.get_output_file_for_nse_indices)
        if self.nse_equities:
            self.loop_through_dates_to(self.get_output_file_for_nse_equities)
        if self.nse_futures:
            self.loop_through_dates_to(self.get_output_file_for_nse_futures)
            if not self.import_selected_nse_futures:
                logger.info("Complete import of NSE Futures data.")
            else:
                logger.info("Selected import of NSE Futures data.")
                self.create_selected_nse_futures_file()
        return self.ami_import_file_list

    def loop_through_dates_to(self, function):
        """
        Loops through start_date to end_date and calls the function
        given as argument for each date.

        :param function: the function/method to be called for each date
        """
        self.current_date = self.start_date
        while self.current_date <= self.end_date:
            function()
            self.current_date += self.time_delta
        self.current_date = self.start_date

    def get_output_file_for_nse_indices(self):
        """
        Generates the file name for current date for NSE Indices and
        appends its location to self.ami_import_file_list if the file
        exists.
        """
        file = 'NSE-Indices-{date}.csv'.format(
            date=self.current_date.strftime('%Y-%m-%d'))
        self.file_location = os.path.join(self.nse_indices_folder, file)
        self.append_file_location_to_list(self.ami_import_file_list)

    def get_output_file_for_nse_equities(self):
        """
        Generates the file name for current date for NSE Equities and
        appends its location to self.ami_import_file_list if the file
        exists.
        """
        file = 'NSE-Equities-{date}.csv'.format(
            date=self.current_date.strftime('%Y-%m-%d'))
        self.file_location = os.path.join(self.nse_equities_folder, file)
        self.append_file_location_to_list(self.ami_import_file_list)

    def get_output_file_for_nse_futures(self):
        """
        Generates the file name for current date for NSE Futures and
        appends its location to self.ami_import_file_list if the file
        exists.
        """
        file = 'NSE-Futures-{date}.csv'.format(
            date=self.current_date.strftime('%Y-%m-%d'))
        self.file_location = os.path.join(self.nse_futures_folder, file)
        if self.import_selected_nse_futures:
            file_list = self.nse_futures_file_list
        else:
            file_list = self.ami_import_file_list
        self.append_file_location_to_list(file_list)

    def append_file_location_to_list(self, file_list):
        """
        Appends the file_location to list if the file exists on disk.

        :param file_list: the list to which files should be appended
        :type file_list: list
        """
        if os.path.exists(self.file_location):
            file_list.append(self.file_location)

    def create_selected_nse_futures_file(self):
        """
        Reads the csv files for NSE Futures, filters the data for
        selected scrips, writes it to a single file in present working
        directory as 'selected_nse_futures.csv' and appends this file to
        the list of files to be imported in Amibroker.
        """
        self.read_csv_files_as_list(self.nse_futures_file_list)
        self.generate_selected_nse_futures_data()
        self.file_location = os.path.join(os.getcwd(),
                                          "selected_nse_futures.csv")
        self.write_selected_nse_futures_data()
        self.append_file_location_to_list(self.ami_import_file_list)

    def generate_selected_nse_futures_data(self):
        """
        Filters the data for selected NSE Futures scrips and returns it
        as a list.

        :return: data for selected NSE Futures scrips
        :rtype: list
        """
        self.get_selected_nse_futures_scrips()
        self.selected_nse_futures_data = []
        for r in self.output_data:
            if r[0] == 'NIFTY-I':
                line = ('ADINIFTY-1', r[1], r[2], r[3], r[4], r[5], '0', '0')
                self.selected_nse_futures_data.append(line)
            if r[0] in self.selected_nse_futures_scrips:
                self.selected_nse_futures_data.append(r)
        return self.selected_nse_futures_data

    def write_selected_nse_futures_data(self):
        """
        Writes the data for selected NSE Futures scrips in a single file.
        """
        header = 'Symbol', 'Date', 'Open', 'High', 'Low', 'Close', 'Volume', \
                 'OI'
        if self.selected_nse_futures_data:
            with open(self.file_location, 'w', newline='') as new:
                csv.writer(new, delimiter=',').writerow(header)
                csv.writer(new, delimiter=',').writerows(
                    self.selected_nse_futures_data)

    def get_selected_nse_futures_scrips(self):
        """
        Creates a list of selected NSE Futures scrips and returns it.
        The selected scrips are Future Indices and VIX for Near-month
        and Next-month contracts.

        :returns: selection of Nse Futures scrips
        :rtype: list
        """
        self.selected_nse_futures_scrips = []
        scrips = ['BANKNIFTY', 'CNXINFRA', 'CNXIT', 'CNXPSE', 'DJIA',
                  'FTSE100', 'MINIFTY', 'NFTYMCAP50', 'NIFTY', 'S&P500',
                  'INDIAVIX']
        months = ['-I', '-II']
        for scrip in scrips:
            for month in months:
                self.selected_nse_futures_scrips.append(scrip + month)
        return self.selected_nse_futures_scrips

    def read_csv_files_as_list(self, file_list):
        """
        Takes a list of files, reads them and returns it as a list.

        :param file_list: list of csv files to be read
        :type file_list: list

        :returns: data read from all the csv files
        :rtype: list
        """
        self.output_data = []
        for file in file_list:
            with open(file, 'r') as data_file:
                self.output_data += list(csv.reader(data_file, delimiter=','))
        return self.output_data

    def generate_indices(self):
        logger.info("Generating indices...")
        self.get_ui_values()
        self.log_window_state()
        self.get_config_values()

    def log_window_state(self):
        """
        Logs the values of the UI widgets.
        """
        logger.debug("Start date: {0}".format(self.start_date))
        logger.debug("End date: {0}".format(self.end_date))
        logger.debug("Ignore Weekend: {0}".format(str(self.ignore_weekend)))
        logger.debug("NSE Indices: {0}".format(str(self.nse_indices)))
        logger.debug("NSE Equities: {0}".format(str(self.nse_equities)))
        logger.debug("NSE Futures: {0}".format(str(self.nse_futures)))
        logger.debug("Debugging: {0}".format(str(self.debugging)))

    def show_preferences_dialog(self):
        """
        Launches the Preferences dialog for the application.
        """
        logger.info("Opening the Preferences dialog.")
        preferences_dialog = PreferencesDialog(parent=self)
        preferences_dialog.show()


if __name__ == "__main__":
    app = QtGui.QApplication(sys.argv)
    window = BoringGorilla()
    app.setActiveWindow(window)
    window.show()
    sys.exit(app.exec_())
